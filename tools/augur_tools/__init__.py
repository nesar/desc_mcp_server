@validate_call
def augur_list_examples() -> ArtifactResult:
    """List augur's shipped example forecast configs, SRD data files and parameter conventions.

    Reads (read-only) the augur clone's examples/*.yml and data/ (DESC_AUGUR_DIR
    or the sibling checkout). For each example: survey year, probes, bin
    layout, number densities, covariance type, transfer function, varied
    parameters, step, priors, and whether it would run as shipped (the
    validator verdict - the SRD examples list priors for parameters they do
    not vary and are 'no-go' until trimmed, which augur_generate_forecast_config
    does automatically). Use it to pick a starting point; then call
    augur_generate_forecast_config rather than copying a YAML (the examples
    use Jinja {{ env['AUGUR_DIR'] }} paths).
    """
    clone = clone_dir("augur")
    examples: dict = {}
    data_files: dict = {}
    if clone is not None:
        for path in sorted((clone / "examples").glob("*.yml")) + sorted((clone / "augur" / "tests").glob("test.yaml")):
            try:
                cfg = _render_yaml_text(path)
                errors, warns, info = _validate(cfg)
                stats = cfg.get("statistics") or {}
                fisher = cfg.get("fisher") or {}
                vp = fisher.get("var_pars") or list((fisher.get("parameters") or {}).keys())
                priors = fisher.get("gaussian_priors") or {}
                examples[path.name] = {
                    "path": str(path),
                    "survey_year": "Y10" if "y10" in path.name.lower() else ("Y1" if "y1" in path.name.lower() else "custom"),
                    "probes": sorted(stats.keys()),
                    "n_source_bins": (cfg.get("sources") or {}).get("nbins"),
                    "n_lens_bins": (cfg.get("lenses") or {}).get("nbins"),
                    "ndens_source_arcmin2": (cfg.get("sources") or {}).get("ndens"),
                    "ndens_lens_arcmin2": (cfg.get("lenses") or {}).get("ndens"),
                    "nz_type": {"sources": (cfg.get("sources") or {}).get("Nz_type"),
                                "lenses": (cfg.get("lenses") or {}).get("Nz_type")},
                    "cov_type": (cfg.get("cov_options") or {}).get("cov_type"),
                    "transfer_function": (cfg.get("cosmo") or {}).get("transfer_function", "boltzmann_camb"),
                    "n_var_pars": len(vp), "var_pars": vp,
                    "step": fisher.get("step"), "derivative_method": fisher.get("derivative_method"),
                    "n_gaussian_priors": len(priors),
                    "priors_not_in_var_pars": [p for p in priors if p not in vp],
                    "has_fisher_bias": "fisher_bias" in fisher,
                    "has_mg": "mg_parametrization" in (cfg.get("cosmo") or {}),
                    "runs_as_shipped": not errors,
                    "validator_errors": errors[:6],
                    "n_data_before_cuts": info.get("n_data_before_cuts"),
                }
            except Exception as exc:  # noqa: BLE001
                examples[path.name] = {"path": str(path), "error": f"{type(exc).__name__}: {exc}"}
        for path in sorted((clone / "data").glob("*")):
            entry = {"path": str(path), "bytes": path.stat().st_size}
            try:
                if path.suffix == ".txt":
                    arr = np.loadtxt(path)
                    entry.update({"shape": list(arr.shape), "format": "ascii: column 0 = z, columns 1.. = n(z) per bin",
                                  "z_range": [float(arr[0, 0]), float(arr[-1, 0])], "n_bins": int(arr.shape[1] - 1)})
                elif "cov" in path.name:
                    arr = np.load(path, mmap_mode="r")
                    entry.update({"shape": list(arr.shape),
                                  "format": "SRD v1 3x2pt covariance, 20 ells per tracer-pair block, "
                                            "fixed pair order (see CAVEATS)"})
                else:
                    entry["format"] = "npy dict {redshift_range, bins}"
            except Exception as exc:  # noqa: BLE001
                entry["error"] = str(exc)
            data_files[path.name] = entry
    message = (f"{len(examples)} example configs and {len(data_files)} data files in the augur clone."
               if clone is not None else
               "augur clone not available (set DESC_AUGUR_DIR); conventions and presets only.")
    return ArtifactResult(
        status="success", files=[], message=message,
        metadata={"augur_clone": str(clone) if clone else None, "examples": examples,
                  "data_files": data_files, "srd_presets": SRD_PRESETS,
                  "conventions": CONVENTIONS, "caveats": CAVEATS,
                  "next": "augur_generate_forecast_config(survey_year=..., probes=...)"})


@validate_call
def augur_generate_forecast_config(
    output_dir: Annotated[str, Field(min_length=1)],
    survey_year: Annotated[Literal["Y1", "Y10"], Field(description="LSST SRD year: sets bins (5/5 vs 5/10), ndens (10/18 vs 27/48 arcmin^-2), kmax, lens biases, n(z) files, SRD covariance.")] = "Y1",
    probes: Annotated[Literal["3x2pt", "shear", "clustering", "ggl"], Field(description="shear = cosmic shear only (sources), clustering = lens auto-spectra, ggl = galaxy-galaxy lensing, 3x2pt = all three.")] = "3x2pt",
    n_source_bins: Annotated[int | None, Field(ge=1, le=10, description="Source tomographic bins; None = SRD (5). nz_mode='file' allows at most 5.")] = None,
    n_lens_bins: Annotated[int | None, Field(ge=1, le=12, description="Lens bins; None = SRD (Y1: 5, Y10: 10). nz_mode='file' allows at most 5 (Y1) / 10 (Y10).")] = None,
    ndens_source: Annotated[float | None, Field(gt=0, le=100, description="Total source density [arcmin^-2]; None = SRD (Y1 10, Y10 27).")] = None,
    ndens_lens: Annotated[float | None, Field(gt=0, le=200, description="Total lens density [arcmin^-2]; None = SRD (Y1 18, Y10 48).")] = None,
    sigma_e: Annotated[float, Field(gt=0, le=1, description="Per-component shape noise.")] = 0.26,
    ell_min: Annotated[float, Field(ge=2, le=1000)] = 20.0,
    ell_max: Annotated[float, Field(ge=50, le=30000)] = 15000.0,
    n_ell: Annotated[int, Field(ge=3, le=100, description="Number of log-spaced ell bands (SRD: 20).")] = 20,
    kmax: Annotated[float | None, Field(gt=0, le=5, description="Scale cut for probes with lenses [Mpc^-1, NO h]; converted to lmax = kmax*chi(z_mean). None = SRD (0.202 / 0.201). Ignored when lmax is given.")] = None,
    lmax: Annotated[float | None, Field(ge=10, le=30000, description="Alternative to kmax: a fixed multipole cut for lens probes.")] = None,
    shear_lmax: Annotated[float | None, Field(ge=10, le=30000, description="Optional multipole cut for cosmic shear (SRD applies none).")] = None,
    cov_type: Annotated[Literal["gaus_internal", "SRD", "tjpcov"], Field(description="gaus_internal = augur's mode-counting Gaussian (any layout, fast); SRD = the DESC SRD v1 covariance (requires the exact SRD layout, 3x2pt only); tjpcov = TJPCov Gaussian f_sky (slow).")] = "gaus_internal",
    fsky: Annotated[float | None, Field(gt=0, le=1, description="Sky fraction for gaus_internal/tjpcov; None = SRD-like (Y1 0.3, Y10 0.4).")] = None,
    cosmology: Annotated[CosmologyParams | None, Field(description="Fiducial cosmology; None = DESC SRD values with eisenstein_hu + halofit (fast). boltzmann_camb gets halofit_version=takahashi automatically.")] = None,
    var_pars: Annotated[list[str] | None, Field(description="Parameters to vary (firecrown names). None = SRD set: Omega_c, sigma8, n_s, w0, wa, Omega_b, h, lens0_bias, lens1_bias (lens biases only when lenses exist).")] = None,
    step: Annotated[float, Field(gt=0, le=0.5, description="ABSOLUTE finite-difference step in parameter units.")] = 0.01,
    derivative_method: Annotated[Literal["numdifftools", "5pt_stencil", "derivkit"], Field(description="numdifftools: 2n+1 evaluations; 5pt_stencil: 4n+1; derivkit: ~27n (adaptive).")] = "numdifftools",
    gaussian_priors: Annotated[dict[str, float] | None, Field(description="{param: 1-sigma width}; every key must be in var_pars (checked here).")] = None,
    srd_priors: Annotated[bool, Field(description="Add the SRD prior widths (Omega_c 0.2, Omega_b 0.006, h 0.063, n_s 0.08, sigma8 0.14, w0 0.8, wa 2.0, biases 0.9, delta_z 0.002/0.005, m 0.013, IA 3.9/2.3) for the parameters that ARE varied.")] = False,
    fisher_bias_params: Annotated[dict[str, float] | None, Field(description="Optional Fisher-bias probe: {param: shifted value} evaluated as a 'wrong' data vector (e.g. {'Omega_c': 0.27}).")] = None,
    transform_S8: Annotated[bool, Field(description="Report the Fisher matrix in S8 instead of sigma8 (needs sigma8 in var_pars).")] = False,
    transform_Omega_m: Annotated[bool, Field(description="Report in Omega_m instead of Omega_c (needs Omega_c in var_pars).")] = False,
    nz_mode: Annotated[Literal["file", "analytic"], Field(description="file = the SRD n(z) tables shipped with augur (ZDistFromFile); analytic = SourceSRD2018/LensSRD2018 parametric n(z) (any bin count).")] = "file",
    lens_bias: Annotated[list[float] | None, Field(description="Fiducial linear bias per lens bin; None = SRD values (or 1.0 + 0.1 i beyond the SRD count).")] = None,
    ggl_pairs: Annotated[list[list[int]] | None, Field(description="[lens_i, src_j] pairs for galaxy-galaxy lensing; None = SRD list when the layout matches, else all pairs.")] = None,
    label: Annotated[str | None, Field(description="Short tag for file names.")] = None,
) -> ArtifactResult:
    """Write a complete, Jinja-free augur forecast YAML (absolute paths) for an LSST Y1/Y10 forecast.

    Encodes the DESC SRD setups exactly like augur/examples/srd_y1_3x2.yml and
    srd_y10_3x2.yml (eisenstein_hu + halofit, SRD n(z) tables, lens biases, IA
    fiducials, 20 log-spaced ell bands 20..15000, kmax 0.2 Mpc^-1 on lens
    probes, general.ignore_scale_cuts=True with likelihood-side cuts) but
    with every path absolute and the prior list trimmed to var_pars, so the
    result validates and runs as written. Units: ndens arcmin^-2, kmax Mpc^-1
    (no h), ell dimensionless, step ABSOLUTE. Outputs: <output_dir>/augur_<label>_<slug>/
    forecast_config.yml + forecast_config.json (echo), with the sacc and augur
    text outputs destined for the same directory. Metadata reports the
    expected data-vector size, the evaluation count (2n+1 for numdifftools)
    and whether the SRD covariance layout matches. Next: augur_validate_forecast_config,
    then augur_generate_synthetic_datavector / augur_compute_fisher.
    """
    preset = SRD_PRESETS[survey_year]
    data_dir = _augur_data_dir()
    use_src = probes in ("3x2pt", "shear", "ggl")
    use_lens = probes in ("3x2pt", "clustering", "ggl")
    ns = n_source_bins if n_source_bins is not None else preset["n_source_bins"]
    nl = n_lens_bins if n_lens_bins is not None else preset["n_lens_bins"]
    nd_s = ndens_source if ndens_source is not None else preset["ndens_source"]
    nd_l = ndens_lens if ndens_lens is not None else preset["ndens_lens"]
    kmax_v = kmax if kmax is not None else preset["kmax"]
    fsky_v = fsky if fsky is not None else preset["fsky"]
    spec = cosmology or CosmologyParams(preset="desc_srd", transfer_function="eisenstein_hu")

    if nz_mode == "file":
        src_cols = 5
        lens_cols = preset["n_lens_bins"]
        if use_src and ns > src_cols:
            raise ValueError(f"nz_mode='file': the SRD {survey_year} source table has {src_cols} bins; "
                             f"use nz_mode='analytic' for {ns} bins")
        if use_lens and nl > lens_cols:
            raise ValueError(f"nz_mode='file': the SRD {survey_year} lens table has {lens_cols} bins; "
                             f"use nz_mode='analytic' for {nl} bins")
    # cosmology -> augur cosmo block
    if spec.baryons != "none":
        raise ValueError("augur ignores baryonic_effects; set cosmology.baryons='none'")
    if spec.mg_mu0 or spec.mg_sigma0:
        raise ValueError("mu-Sigma MG forecasts are not generated here: start from "
                         "augur/examples/srd_y1_3x2_mg.yml by hand")
    if spec.matter_power_spectrum not in ("halofit", "linear", "camb_hmcode"):
        raise ValueError(f"augur supports matter_power_spectrum halofit/linear/camb_hmcode, "
                         f"not {spec.matter_power_spectrum}")
    if spec.transfer_function == "eisenstein_hu_nowiggles":
        raise ValueError("augur's transfer-function registry has no eisenstein_hu_nowiggles; use eisenstein_hu")
    cosmo_block = dict(spec.firecrown_params())
    cosmo_block["mass_split"] = spec.mass_split
    cosmo_block["transfer_function"] = spec.transfer_function
    if spec.matter_power_spectrum == "camb_hmcode":
        if spec.transfer_function != "boltzmann_camb":
            raise ValueError("camb_hmcode needs transfer_function='boltzmann_camb'")
        cosmo_block["matter_power_spectrum"] = "camb"
        cosmo_block["extra_parameters"] = {"camb": {"halofit_version": "mead2020_feedback",
                                                     "HMCode_logT_AGN": spec.hmcode_logT_AGN,
                                                     "kmax": 20.0}}
    else:
        cosmo_block["matter_power_spectrum"] = spec.matter_power_spectrum
        if spec.transfer_function == "boltzmann_camb":
            cosmo_block["extra_parameters"] = {"camb": {"halofit_version": "takahashi",
                                                         "dark_energy_model": "ppf"}}
    # systematics block
    systematics: dict[str, float] = {}
    if use_src:
        for i in range(ns):
            systematics[f"src{i}_mult_bias"] = 0.0
            systematics[f"src{i}_delta_z"] = 0.0
        systematics.update(IA_FIDUCIAL)
    biases = []
    if use_lens:
        base = list(preset["lens_bias"])
        if lens_bias is not None:
            if len(lens_bias) != nl:
                raise ValueError(f"lens_bias has {len(lens_bias)} entries, n_lens_bins is {nl}")
            biases = [float(b) for b in lens_bias]
        else:
            biases = [base[i] if i < len(base) else round(1.0 + 0.1 * i, 3) for i in range(nl)]
        for i in range(nl):
            systematics[f"lens{i}_bias"] = biases[i]
            systematics[f"lens{i}_alphaz"] = 0.0
            systematics[f"lens{i}_z_piv"] = 0.0
            systematics[f"lens{i}_alphag"] = 0.0
            systematics[f"lens{i}_delta_z"] = 0.0
            systematics[f"lens{i}_sigma_z"] = 1.0
    # var_pars + priors
    if var_pars is None:
        var_pars = ["Omega_c", "sigma8", "n_s", "w0", "wa", "Omega_b", "h"]
        if spec.sigma8 is None:
            var_pars[1] = "A_s"
        if use_lens:
            var_pars += [f"lens{i}_bias" for i in range(min(2, nl))]
    known = set(COSMO_KEYS) | set(systematics)
    unknown = [p for p in var_pars if p not in known]
    if unknown:
        raise ValueError(f"var_pars not in the cosmology or systematics of this setup: {unknown}. "
                         f"Available nuisance parameters: {sorted(systematics)}")
    if "sigma8" in var_pars and spec.sigma8 is None:
        raise ValueError("sigma8 in var_pars but the cosmology is specified with A_s")
    if "A_s" in var_pars and spec.A_s is None:
        raise ValueError("A_s in var_pars but the cosmology is specified with sigma8")
    priors: dict[str, float] = {}
    if srd_priors:
        for p in var_pars:
            if p in SRD_PRIOR_WIDTHS:
                priors[p] = SRD_PRIOR_WIDTHS[p]
            elif p.endswith("_mult_bias"):
                priors[p] = SRD_PRIOR_PATTERNS["_mult_bias"]
            elif p.endswith("_delta_z"):
                priors[p] = SRD_PRIOR_PATTERNS["lens_delta_z" if p.startswith("lens") else "src_delta_z"]
            elif p.endswith("_bias"):
                priors[p] = SRD_PRIOR_PATTERNS["_bias"]
    if gaussian_priors:
        bad = [p for p in gaussian_priors
               if not (p in var_pars or (p == "Omega_m" and transform_Omega_m) or (p == "S8" and transform_S8))]
        if bad:
            raise ValueError(f"gaussian_priors for parameters not in var_pars: {bad} (augur would raise)")
        priors.update({k: float(v) for k, v in gaussian_priors.items()})
    if transform_Omega_m and "Omega_c" not in var_pars:
        raise ValueError("transform_Omega_m needs Omega_c in var_pars")
    if transform_S8 and "sigma8" not in var_pars:
        raise ValueError("transform_S8 needs sigma8 in var_pars")
    if fisher_bias_params:
        if transform_S8 or transform_Omega_m:
            raise ValueError("Fisher bias cannot be combined with the S8/Omega_m transforms (augur refuses)")
        bad = [p for p in fisher_bias_params if p not in known]
        if bad:
            raise ValueError(f"fisher_bias_params not in the model: {bad}")

    # tracers
    sources = lenses = None
    if use_src:
        if nz_mode == "file":
            nz_kw = {"input_file": str(data_dir / preset["nz_source_file"]), "format": "ascii"}
            nz_type = "ZDistFromFile"
        else:
            nz_kw = dict(preset["source_nz"])
            nz_type = "SourceSRD2018"
        sources = {"nbins": ns, "ndens": float(nd_s), "ellipticity_error": float(sigma_e),
                   "Nz_type": nz_type, "Nz_kwargs": nz_kw}
    if use_lens:
        if nz_mode == "file":
            nz_kw = {"input_file": str(data_dir / preset["nz_lens_file"]), "format": "ascii"}
            nz_type = "ZDistFromFile"
        else:
            lp = dict(preset["lens_nz"])
            centers = list(lp.pop("Nz_center"))
            width = lp["Nz_width"]
            if nl != len(centers):  # re-slice 0.2..1.2 into nl bins of equal width
                width = round(1.0 / nl, 4)
                centers = [round(0.2 + width * (i + 0.5), 4) for i in range(nl)]
                lp["Nz_width"] = width
            nz_kw = {"Nz_center": centers, **lp}
            nz_type = "LensSRD2018"
        lenses = {"nbins": nl, "ndens": float(nd_l), "Nz_type": nz_type, "Nz_kwargs": nz_kw}

    # statistics
    edges_str = f"np.geomspace({ell_min:g}, {ell_max:g}, {n_ell + 1}, endpoint=True)"
    edges = np.geomspace(ell_min, ell_max, n_ell + 1)
    layout_is_srd = (ns == preset["n_source_bins"] and nl == preset["n_lens_bins"] and n_ell == 20
                     and abs(ell_min - 20) < 1e-9 and abs(ell_max - 15000) < 1e-9)
    statistics: dict = {}
    if probes in ("3x2pt", "shear"):
        statistics["galaxy_shear_cl_ee"] = {"tracer_combs": _pairs_all(ns, ns, True), "ell_edges": edges_str}
        if shear_lmax is not None:
            statistics["galaxy_shear_cl_ee"]["lmax"] = float(shear_lmax)
    lens_cut = {"lmax": float(lmax)} if lmax is not None else {"kmax": float(kmax_v)}
    if probes in ("3x2pt", "ggl"):
        if ggl_pairs is not None:
            pairs = [[int(a), int(b)] for a, b in ggl_pairs]
            for a, b in pairs:
                if not (0 <= a < nl and 0 <= b < ns):
                    raise ValueError(f"ggl pair [lens{a}, src{b}] out of range (lenses {nl}, sources {ns})")
        elif ns == preset["n_source_bins"] and nl == preset["n_lens_bins"]:
            pairs = [list(p) for p in preset["ggl_pairs"]]
        else:
            pairs = _pairs_all(nl, ns, False)
        statistics["galaxy_shearDensity_cl_e"] = {"tracer_combs": pairs, "ell_edges": edges_str, **lens_cut}
    if probes in ("3x2pt", "clustering"):
        statistics["galaxy_density_cl"] = {"tracer_combs": [[i, i] for i in range(nl)],
                                           "ell_edges": edges_str, **lens_cut}
    # covariance
    if cov_type == "SRD":
        cov_opts = {"cov_type": "SRD", "SRD_cov_path": str(data_dir / preset["srd_cov_file"])}
    elif cov_type == "tjpcov":
        cov_opts = {"cov_type": "tjpcov", "fsky": float(fsky_v), "IA": None,
                    "binning_info": {"ell_edges": edges_str}}
    else:
        cov_opts = {"cov_type": "gaus_internal", "fsky": float(fsky_v)}

    # paths
    tag = label or f"{survey_year}_{probes}"
    slug = param_slug({"year": survey_year, "probes": probes, "ns": ns, "nl": nl, "nd": (nd_s, nd_l),
                       "ell": (ell_min, ell_max, n_ell), "cut": (kmax_v, lmax, shear_lmax),
                       "cov": cov_type, "fsky": fsky_v, "cosmo": spec.slug(), "var": tuple(var_pars),
                       "step": step, "method": derivative_method, "priors": tuple(sorted(priors.items())),
                       "bias": tuple(sorted((fisher_bias_params or {}).items())), "nz": nz_mode,
                       "t": (transform_S8, transform_Omega_m), "sig": sigma_e})
    run_dir = resolve_outdir(output_dir) / f"augur_{tag}_{slug}"
    run_dir.mkdir(parents=True, exist_ok=True)
    (run_dir / "augur_out").mkdir(exist_ok=True)

    config = {
        "fiducial_sacc_path": str(run_dir / "fiducial_datavector.sacc"),
        "general": {"ignore_scale_cuts": True, "ignore_scale_cuts_likelihood": False,
                    "bandpower_windows": "None"},
        "cosmo": cosmo_block,
        "ccl_accuracy": {"spline_params": {"K_MAX_SPLINE": 100}},
        "systematics": systematics,
        "Firecrown_Factory": copy.deepcopy(FIRECROWN_FACTORY),
    }
    if sources:
        config["sources"] = sources
    if lenses:
        config["lenses"] = lenses
    config["statistics"] = statistics
    config["cov_options"] = cov_opts
    fisher = {"var_pars": list(var_pars), "step": float(step), "derivative_method": derivative_method,
              "output": str(run_dir / "augur_out" / "fisher.dat"),
              "fid_output": str(run_dir / "augur_out" / "fiducials.dat")}
    if priors:
        fisher["gaussian_priors"] = priors
    if transform_S8:
        fisher["transform_S8"] = True
    if transform_Omega_m:
        fisher["transform_Omega_m"] = True
    if fisher_bias_params:
        fisher["fisher_bias"] = {"biased_dv": "", "bias_params": {k: float(v) for k, v in fisher_bias_params.items()}}
    config["fisher"] = fisher

    errors, warns, info = _validate(config)
    if errors:  # should not happen - surface loudly rather than write a broken file
        raise ValueError("generated config fails validation: " + "; ".join(errors))

    import yaml
    yml_path = run_dir / "forecast_config.yml"
    yml_path.write_text(
        f"# augur forecast config generated by desc-mcp-server ({survey_year} {probes}, {spec.label()})\n"
        "# Units: ndens arcmin^-2, kmax Mpc^-1 (no h), ells dimensionless, fisher.step ABSOLUTE.\n"
        + yaml.safe_dump(config, sort_keys=False, default_flow_style=None, width=100),
        encoding="utf-8")
    json_path = run_dir / "forecast_config.json"
    write_json(json_path, {"config": config, "survey_year": survey_year, "probes": probes,
                           "cosmology": spec.model_dump(), "label": tag})

    n_pairs = {k: len(v["tracer_combs"]) for k, v in statistics.items()}
    n_par = len(var_pars)
    evals = {"numdifftools": 2 * n_par + 1, "5pt_stencil": 4 * n_par + 1, "derivkit": 27 * n_par}[derivative_method]
    srd_cov_possible = layout_is_srd and probes == "3x2pt" and (
        ggl_pairs is None or sorted(map(list, ggl_pairs)) == sorted(map(list, preset["ggl_pairs"])))
    metadata = {
        "config_path": str(yml_path), "run_dir": str(run_dir), "survey_year": survey_year, "probes": probes,
        "n_source_bins": ns if use_src else 0, "n_lens_bins": nl if use_lens else 0,
        "ndens_arcmin2": {"source": nd_s if use_src else None, "lens": nd_l if use_lens else None},
        "ell_bands": {"n": n_ell, "edges": [round(float(e), 3) for e in edges]},
        "scale_cuts": {"lens_probes": lens_cut, "shear_lmax": shear_lmax, "kmax_units": "Mpc^-1 (no h)"},
        "n_pairs": n_pairs, "n_data_before_cuts": info.get("n_data_before_cuts"),
        "cov_type": cov_type, "fsky": fsky_v if cov_type != "SRD" else None,
        "srd_covariance_layout_match": srd_cov_possible,
        "cosmology": spec.model_dump(),
        "cosmology_label": spec.label(),
        "var_pars": list(var_pars), "gaussian_priors": priors, "step_absolute": step,
        "derivative_method": derivative_method,
        "estimated_likelihood_evaluations": evals + 1 + (2 if fisher_bias_params else 0),
        "fisher_bias_params": fisher_bias_params or None,
        "validator": {"errors": errors, "warnings": warns},
        "nuisance_parameters_available": sorted(systematics),
        "units": CONVENTIONS,
    }
    msg = (f"Wrote augur {survey_year} {probes} forecast config ({sum(n_pairs.values())} tracer pairs x "
           f"{n_ell} ells = {info.get('n_data_before_cuts')} data points before cuts; {n_par} varied "
           f"parameters -> ~{metadata['estimated_likelihood_evaluations']} likelihood evaluations; "
           f"cov {cov_type}).")
    if cov_type != "SRD" and srd_cov_possible:
        msg += " Layout matches the SRD covariance: cov_type='SRD' is available."
    return ArtifactResult(status="success", files=[str(yml_path), str(json_path)], message=msg, metadata=metadata)


@validate_call
def augur_validate_forecast_config(
    config_path: Annotated[str, Field(min_length=1, description="Path to an augur YAML (ours or a shipped example; Jinja AUGUR_DIR tags are rendered with the clone path).")],
) -> ArtifactResult:
    """Check an augur forecast YAML for the known traps before any (possibly remote) run; returns go/no-go.

    Pure-python, milliseconds. Errors (no-go): gaussian_priors keys not in
    var_pars (unless Omega_m/S8 with the transform), both or neither of
    sigma8/A_s, kmax AND lmax keys on one statistic, cov_type SRD without the
    exact SRD layout (5/5 or 5/10 bins, SRD pair lists, all three statistics,
    20 ells), ignore_scale_cuts_likelihood=True with a Firecrown_Factory
    (silently drops systematics), boltzmann_camb without
    extra_parameters.camb.halofit_version, Nz_type not in augur's registry,
    missing n(z)/covariance files, tracer indices out of range, unknown
    var_pars, bad step/method, fisher_bias + transforms. Warnings: relative
    paths, tiny/large ABSOLUTE steps, differing ell edges, legacy likelihood.
    Metadata also gives the data-vector size and the expected number of
    likelihood evaluations (cost estimate for dispatch).
    """
    cfg = _load_config(config_path)
    errors, warns, info = _validate(cfg)
    verdict = "go" if not errors else "no-go"
    return ArtifactResult(
        status="success", files=[],
        message=f"{verdict}: {len(errors)} errors, {len(warns)} warnings for {config_path}.",
        metadata={"verdict": verdict, "ok": not errors, "errors": errors, "warnings": warns, **info,
                  "config_path": str(Path(config_path).expanduser().resolve())})


def _plot_datavector(rows: list[dict], path: Path, title: str) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from ..plotting import LINESTYLES, PALETTE, rc_params

    stats = sorted({r["stat"] for r in rows})
    with plt.rc_context(rc_params(11)):
        fig, axes = plt.subplots(1, len(stats), figsize=(5.2 * len(stats), 4.2), constrained_layout=True,
                                 squeeze=False)
        for ax, stat in zip(axes[0], stats):
            pairs = sorted({(r["tr1"], r["tr2"]) for r in rows if r["stat"] == stat})
            for k, (t1, t2) in enumerate(pairs):
                sel = [r for r in rows if r["stat"] == stat and r["tr1"] == t1 and r["tr2"] == t2]
                ell = np.array([r["ell"] for r in sel])
                cl = np.array([r["cl"] for r in sel])
                sig = np.array([r["sigma"] or 0.0 for r in sel])
                keep = np.array([r["in_likelihood"] for r in sel])
                color = PALETTE[k % len(PALETTE)]
                ls = LINESTYLES[(k // len(PALETTE)) % len(LINESTYLES)]
                ax.errorbar(ell[keep], np.abs(cl[keep]), yerr=sig[keep], color=color, ls=ls, lw=1.2,
                            capsize=1.5, label=f"{t1}-{t2}" if len(pairs) <= 10 else None)
                if (~keep).any():
                    ax.plot(ell[~keep], np.abs(cl[~keep]), color=color, ls=":", lw=0.8, alpha=0.5)
            ax.set_xscale("log")
            ax.set_yscale("log")
            ax.set_xlabel(r"Multipole $\ell$")
            ax.set_ylabel(r"$|C_\ell|$")
            ax.set_title(f"{stat} ({len(pairs)} pairs)")
            if len(pairs) <= 10:
                ax.legend(ncol=2, fontsize=7)
        fig.suptitle(title, fontsize=11)
        fig.savefig(path, dpi=150)
        plt.close(fig)


@validate_call
def augur_generate_synthetic_datavector(
    output_dir: Annotated[str, Field(min_length=1)],
    config_path: Annotated[str, Field(min_length=1, description="Forecast YAML from augur_generate_forecast_config (validated).")],
    env_setup: Annotated[str | None, Field(description="Facility environment activation (only used when dispatch is remote), e.g. the NERSC desc-python snippet from export_dispatch_pack.")] = None,
    plot: Annotated[bool, Field(description="Write a PNG of all C_ell with error bars.")] = True,
    duration_s: Annotated[int, Field(ge=120, le=14400, description="Walltime for a remote job.")] = 900,
) -> ArtifactResult:
    """Run augur.generate: fiducial theory C_ell for every tracer pair + covariance -> sacc, CSV, n(z), PNG.

    One likelihood evaluation plus the covariance (gaus_internal: seconds;
    tjpcov: minutes, dispatchable). Writes <output_dir>/datavector_<slug>.csv
    with columns stat, tr1, tr2, ell, cl, sigma (sqrt of the covariance
    diagonal), in_likelihood (0/1: survives the scale cut applied in the
    likelihood; the sacc keeps all ells because general.ignore_scale_cuts=True),
    nz_sources/nz_lenses CSVs (z, nz per bin), cov.npy (full covariance when
    returned, always the diagonal), and a PNG. The sacc file goes to the
    config's fiducial_sacc_path (locally) or the job directory (remote).
    Metadata: total S/N = sqrt(d C^-1 d), per-statistic counts, lmax actually
    kept per pair (kmax converted with chi(z_mean)). Next: augur_compute_fisher.
    """
    cfg = _load_config(config_path)
    errors, warns, info = _validate(cfg)
    if errors:
        raise ValueError("config fails validation (run augur_validate_forecast_config): " + "; ".join(errors[:5]))
    out, computed_on = _run_forecast_kernel(cfg, "generate", env_setup, duration_s, max_cov_return=1200)

    outdir = resolve_outdir(output_dir)
    slug = param_slug({"cfg": str(Path(config_path).resolve()), "n": out["n_data"]})
    rows = out["data_vector"]
    label = f"augur synthetic data vector ({out['cov_type']}, {out['n_data']} points)"
    dv_path = outdir / f"datavector_{slug}.csv"
    _write_table(dv_path, [f"label: {label}", "quantity: angular_power_spectra",
                           "units: ell dimensionless, cl dimensionless, sigma = sqrt(diag cov)",
                           f"config: {config_path}", f"sacc: {out['sacc_path']}", f"cov_type: {out['cov_type']}"],
                 {"stat": [r["stat"] for r in rows], "tr1": [r["tr1"] for r in rows],
                  "tr2": [r["tr2"] for r in rows], "ell": [float(r["ell"]) for r in rows],
                  "cl": [float(r["cl"]) for r in rows],
                  "sigma": [float(r["sigma"]) if r["sigma"] is not None else float("nan") for r in rows],
                  "in_likelihood": [int(bool(r["in_likelihood"])) for r in rows]})
    files = [str(dv_path)]
    nz = out.get("nz") or {}
    for kind, fname in (("src", "nz_sources"), ("lens", "nz_lenses")):
        names = sorted([n for n in nz if n.startswith(kind)], key=lambda s: int(s[len(kind):]))
        if names:
            cols = {"z": np.asarray(nz[names[0]]["z"])}
            for n in names:
                cols[f"nz_{n}"] = np.asarray(nz[n]["nz"])
            p = outdir / f"{fname}_{slug}.csv"
            write_csv(p, cols, [f"label: {fname.replace('_', ' ')} n(z)", "quantity: nz",
                                "units: z dimensionless, nz arbitrary normalisation",
                                "zmean: " + ", ".join(f"{n}={nz[n]['zmean']:.3f}" for n in names)])
            files.append(str(p))
    cov = out.get("cov")
    cov_path = outdir / f"cov_{slug}.npy"
    if cov is not None:
        np.save(cov_path, np.asarray(cov, dtype=float))
    else:
        np.save(cov_path, np.asarray(out["cov_diag"], dtype=float))
    files.append(str(cov_path))
    if plot:
        png = outdir / f"datavector_{slug}.png"
        _plot_datavector(rows, png, label)
        files.append(str(png))
    sacc_local = out["sacc_path"] if computed_on == "local" and os.path.isfile(out["sacc_path"]) else None
    if sacc_local:
        files.append(sacc_local)

    snr = None
    if cov is not None:
        d = np.array([r["cl"] for r in rows])
        try:
            snr = float(np.sqrt(d @ np.linalg.solve(np.asarray(cov), d)))
        except np.linalg.LinAlgError:
            snr = None
    per_stat = {}
    for r in rows:
        per_stat.setdefault(r["stat"], {"n_points": 0, "n_in_likelihood": 0, "pairs": set()})
        per_stat[r["stat"]]["n_points"] += 1
        per_stat[r["stat"]]["n_in_likelihood"] += int(bool(r["in_likelihood"]))
        per_stat[r["stat"]]["pairs"].add((r["tr1"], r["tr2"]))
    for v in per_stat.values():
        v["n_pairs"] = len(v.pop("pairs"))
    metadata = {"computed_on": computed_on, "n_data": out["n_data"],
                "n_data_in_likelihood": out["n_data_likelihood"], "per_statistic": per_stat,
                "total_snr": snr, "cov_type": out["cov_type"], "scale_cuts_kept": out["scale_cuts"],
                "sacc_path": out["sacc_path"], "cov_file_is_full_matrix": cov is not None,
                "nz_zmean": {n: nz[n]["zmean"] for n in nz}, "versions": out.get("versions"),
                "timing_s": out.get("timing_s"), "validator_warnings": warns}
    if out.get("_env_check"):
        metadata["env_check"] = out["_env_check"]
    if out.get("_artifact_files"):
        metadata["remote_artifact_files"] = out["_artifact_files"]
    return ArtifactResult(
        status="success", files=files,
        message=f"Synthetic data vector: {out['n_data']} C_ell points ({out['n_data_likelihood']} inside "
                f"the scale cuts) with {out['cov_type']} covariance"
                + (f", total S/N {snr:.0f}" if snr else "") + f"; computed on {computed_on}.",
        metadata=metadata)


