@validate_call
def augur_plot_fisher_contours(
    output_dir: Annotated[str, Field(min_length=1)],
    fisher_csvs: Annotated[list[str], Field(min_length=1, max_length=6, description="One or more fisher*.csv from augur_compute_fisher (overlaid; e.g. Y1 vs Y10, or without/with priors).")],
    params: Annotated[list[str] | None, Field(description="Parameter subset to show (order kept); None = all parameters of the first file (<= 8 recommended).")] = None,
    labels: Annotated[list[str] | None, Field(description="Legend label per file; None = the file's label header.")] = None,
    confidence_levels: Annotated[list[float], Field(description="Ellipse confidence levels (2D), e.g. [0.68, 0.95].")] = [0.68, 0.95],
    fiducials: Annotated[dict[str, float] | None, Field(description="Override the ellipse centres (default: fiducials stored in the CSV header).")] = None,
    title: Annotated[str | None, Field()] = None,
) -> ArtifactResult:
    """Triangle plot of Fisher ellipses (68/95% CL) for a parameter subset, overlaying several Fisher matrices.

    Marginalises each file's Fisher matrix over the parameters not shown
    (Cov = F^-1, then the 2x2 sub-blocks) and draws the CL ellipses with
    augur's scaling (chi2.ppf(CL, 2)), 1-D Gaussians on the diagonal.
    Parameters missing from a file are skipped for that file. Writes
    fisher_contours_<slug>.png. Metadata: per file the marginalised sigmas of
    the shown parameters and the DETF w0-wa FoM when both are present, and
    FoM ratios relative to the first file (e.g. Y10/Y1).
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Ellipse
    from scipy.stats import norm
    from ..plotting import LINESTYLES, PALETTE, rc_params

    for cl in confidence_levels:
        if not (0 < cl < 1):
            raise ValueError("confidence_levels must be in (0, 1)")
    loaded = []
    for k, p in enumerate(fisher_csvs):
        names, F, fid, header = read_fisher_csv(p)
        if fiducials:
            fid.update({n: float(v) for n, v in fiducials.items() if n in fid})
        lab = labels[k] if labels and k < len(labels) else header.get("label", Path(p).stem)
        loaded.append({"path": p, "names": names, "F": F, "fid": fid, "label": lab})
    show = params or list(loaded[0]["names"])
    missing = [n for n in show if n not in loaded[0]["names"]]
    if missing:
        raise ValueError(f"params {missing} not in {fisher_csvs[0]} (has {loaded[0]['names']})")
    if len(show) < 1:
        raise ValueError("need at least one parameter")

    summary = []
    for entry in loaded:
        cov = np.linalg.inv(entry["F"])
        idx = {n: entry["names"].index(n) for n in show if n in entry["names"]}
        entry["cov"] = cov
        entry["idx"] = idx
        sig = {n: float(np.sqrt(cov[i, i])) for n, i in idx.items()}
        fom = _fom_block(entry["F"], entry["names"])
        summary.append({"file": entry["path"], "label": entry["label"], "sigma": sig,
                        "detf_fom_w0wa": fom["detf_fom"] if fom else None})
    npar = len(show)
    with plt.rc_context(rc_params(10)):
        size = max(2.0, min(3.2, 14 / npar))
        fig, axes = plt.subplots(npar, npar, figsize=(size * npar, size * npar), squeeze=False)
        lims = {}
        for n in show:
            s_max = max((e["cov"][e["idx"][n], e["idx"][n]] ** 0.5 for e in loaded if n in e["idx"]), default=1.0)
            c = loaded[0]["fid"].get(n, 0.0)
            lims[n] = (c - 3.2 * s_max, c + 3.2 * s_max)
        for i, pi in enumerate(show):
            for j, pj in enumerate(show):
                ax = axes[i, j]
                if j > i:
                    ax.set_visible(False)
                    continue
                for k, e in enumerate(loaded):
                    color = PALETTE[k % len(PALETTE)]
                    ls = LINESTYLES[k % len(LINESTYLES)]
                    if pi not in e["idx"] or pj not in e["idx"]:
                        continue
                    ci, cj = e["fid"].get(pi, 0.0), e["fid"].get(pj, 0.0)
                    if i == j:
                        s = np.sqrt(e["cov"][e["idx"][pi], e["idx"][pi]])
                        x = np.linspace(*lims[pi], 300)
                        ax.plot(x, norm.pdf(x, ci, s) * s, color=color, ls=ls, label=e["label"] if i == 0 else None)
                    else:
                        ii, jj = e["idx"][pi], e["idx"][pj]
                        sub = e["cov"][np.ix_([jj, ii], [jj, ii])]
                        for m, cl in enumerate(sorted(confidence_levels)):
                            w, h, ang = _ellipse(sub, cl)
                            ax.add_patch(Ellipse((cj, ci), w, h, angle=ang, facecolor=color,
                                                 edgecolor=color, ls=ls, lw=1.3,
                                                 alpha=0.35 if m == 0 else 0.15))
                        ax.plot([cj], [ci], marker="+", color=color, ms=5, mew=0.8)
                if i == j:
                    ax.set_yticks([])
                    ax.set_xlim(*lims[pi])
                    ax.set_ylim(0, 0.45)
                else:
                    ax.set_xlim(*lims[pj])
                    ax.set_ylim(*lims[pi])
                if i == npar - 1:
                    ax.set_xlabel(_label_of(pj))
                else:
                    ax.set_xticklabels([])
                if j == 0 and i > 0:
                    ax.set_ylabel(_label_of(pi))
                elif j > 0:
                    ax.set_yticklabels([])
                ax.tick_params(labelsize=7)
                ax.xaxis.set_major_locator(plt.MaxNLocator(3))
                ax.yaxis.set_major_locator(plt.MaxNLocator(3))
        handles, labs = axes[0, 0].get_legend_handles_labels()
        if handles:
            fig.legend(handles, labs, loc="upper right", frameon=False, fontsize=9,
                       bbox_to_anchor=(0.98, 0.98))
        fig.suptitle(title or f"Fisher contours ({', '.join(f'{cl:.0%}' for cl in sorted(confidence_levels))} CL)",
                     fontsize=11, y=0.995)
        fig.subplots_adjust(wspace=0.08, hspace=0.08, left=0.1, bottom=0.1, right=0.98, top=0.95)
        outdir = resolve_outdir(output_dir)
        slug = param_slug({"files": tuple(fisher_csvs), "params": tuple(show), "cl": tuple(confidence_levels)})
        png = outdir / f"fisher_contours_{slug}.png"
        fig.savefig(png, dpi=160)
        plt.close(fig)

    ratios = {}
    base = summary[0]["detf_fom_w0wa"]
    if base:
        for s in summary[1:]:
            if s["detf_fom_w0wa"]:
                ratios[s["label"]] = float(s["detf_fom_w0wa"] / base)
    return ArtifactResult(
        status="success", files=[str(png)],
        message=f"Triangle plot for {npar} parameters from {len(loaded)} Fisher matrix(es) at "
                f"{', '.join(f'{cl:.0%}' for cl in sorted(confidence_levels))} CL.",
        metadata={"params": show, "confidence_levels": confidence_levels, "per_file": summary,
                  "fom_ratio_to_first": ratios,
                  "note": "sigmas are marginalised over ALL parameters of each Fisher matrix, not only the shown subset"})
