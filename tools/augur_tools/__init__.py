@validate_call
def augur_compute_fisher(
    output_dir: Annotated[str, Field(min_length=1)],
    config_path: Annotated[str, Field(min_length=1, description="Forecast YAML from augur_generate_forecast_config (validated, with a fisher section).")],
    env_setup: Annotated[str | None, Field(description="Facility environment activation when dispatch is remote (export_dispatch_pack lists candidates); ignored locally.")] = None,
    include_bias: Annotated[bool | None, Field(description="Compute the Fisher bias when the config has fisher.fisher_bias (None = yes if present).")] = None,
    derived_params: Annotated[bool, Field(description="Also report sigma(Omega_m) and sigma(S8) by linear propagation when Omega_c / sigma8 are varied.")] = True,
    duration_s: Annotated[int, Field(ge=300, le=28800, description="Walltime for a remote job (2n+1 evaluations; eisenstein_hu ~1 s each for 3x2pt Y1, CAMB ~5 s).")] = 1800,
) -> ArtifactResult:
    """Compute the Fisher matrix (augur.Analyze) -> fisher.csv, priors, marginalised sigmas, w0-wa FoM, derivatives.

    HEAVY: 2n+1 (numdifftools) / 4n+1 (5pt_stencil) full theory-vector
    evaluations for n varied parameters; Y1 3x2pt with eisenstein_hu is ~1 s
    per evaluation, CAMB ~5 s, Y10 roughly twice. Dispatch with env_setup on
    a facility for large runs. Outputs in <output_dir>: fisher_<slug>.csv
    (labelled matrix, fiducials and priors in the header), fisher_with_priors_<slug>.csv
    (when gaussian_priors exist), marginalized_sigmas_<slug>.csv (param,
    fiducial, sigma_no_prior, sigma_with_prior, prior), fom_<slug>.json (DETF
    FoM 1/sqrt(det Cov_w0wa), augur's get_FoM_all at 68/95%, with and without
    priors, plus Omega_m/S8 derived sigmas), derivatives_<slug>.npy (n_par x
    n_data), fisher_bias_<slug>.csv when requested. Checks symmetry and
    positive-definiteness (a non-PD matrix means a degenerate or noisy
    derivative - change step or var_pars). Next: augur_plot_fisher_contours.
    """
    cfg = _load_config(config_path)
    errors, warns, info = _validate(cfg)
    if errors:
        raise ValueError("config fails validation (run augur_validate_forecast_config): " + "; ".join(errors[:5]))
    if "fisher" not in cfg:
        raise ValueError("config has no fisher section")
    out, computed_on = _run_forecast_kernel(cfg, "fisher", env_setup, duration_s,
                                            include_bias=include_bias, max_cov_return=0)

    names = list(out["param_names"])
    F = np.asarray(out["fisher"], dtype=float)
    Fp = np.asarray(out["fisher_with_priors"], dtype=float) if out.get("fisher_with_priors") is not None else None
    fid = [float(v) for v in out["fiducials"]]
    priors = {k: float(v) for k, v in (out.get("priors") or {}).items()}
    # priors on transformed names keep the transformed label
    sym_err = float(np.max(np.abs(F - F.T)) / max(np.max(np.abs(F)), 1e-300))
    eig = np.linalg.eigvalsh(0.5 * (F + F.T))
    pos_def = bool(eig.min() > 0)
    cond = float(eig.max() / eig.min()) if pos_def else None
    cov = np.linalg.inv(F) if pos_def else np.linalg.pinv(F)
    sig = np.sqrt(np.clip(np.diag(cov), 0, None))
    sig_p = None
    if Fp is not None:
        covp = np.linalg.inv(Fp)
        sig_p = np.sqrt(np.clip(np.diag(covp), 0, None))

    outdir = resolve_outdir(output_dir)
    slug = param_slug({"cfg": str(Path(config_path).resolve()), "pars": tuple(names)})
    label = f"augur Fisher ({len(names)} params, {out['derivative_method']}, step {out['step']:g})"
    extra = [f"config: {config_path}", f"derivative_method: {out['derivative_method']}",
             f"step_absolute: {out['step']}", f"n_data: {out['n_data_likelihood']}",
             f"cov_type: {out['cov_type']}", f"computed_on: {computed_on}"]
    f_path = outdir / f"fisher_{slug}.csv"
    _write_fisher_csv(f_path, names, F, fid, priors, label, extra + ["priors_included: no"])
    files = [str(f_path)]
    fp_path = None
    if Fp is not None:
        fp_path = outdir / f"fisher_with_priors_{slug}.csv"
        _write_fisher_csv(fp_path, names, Fp, fid, priors, label + " + Gaussian priors", extra + ["priors_included: yes"])
        files.append(str(fp_path))
    ms_path = outdir / f"marginalized_sigmas_{slug}.csv"
    _write_table(ms_path, [f"label: marginalised 1-sigma errors ({label})", "quantity: marginalized_sigmas",
                           "units: parameter units; sigma = sqrt((F^-1)_ii)", f"config: {config_path}"],
                 {"param": names, "fiducial": fid, "sigma_no_prior": [float(s) for s in sig],
                  "sigma_with_prior": [float(s) for s in sig_p] if sig_p is not None else [float("nan")] * len(names),
                  "prior": [priors.get(n, float("nan")) for n in names]})
    files.append(str(ms_path))
    d_path = outdir / f"derivatives_{slug}.npy"
    np.save(d_path, np.asarray(out["derivatives"], dtype=float))
    files.append(str(d_path))

    cosmo_fid = dict(cfg.get("cosmo") or {})
    fom = {"params": names, "fiducials": dict(zip(names, fid)),
           "sigma_no_prior": dict(zip(names, map(float, sig))),
           "sigma_with_prior": dict(zip(names, map(float, sig_p))) if sig_p is not None else None,
           "priors": priors, "no_prior": _fom_block(F, names) if pos_def else None,
           "with_prior": _fom_block(Fp, names) if Fp is not None else None,
           "fom_definition": "DETF: 1/sqrt(det Cov(w0,wa)) with Cov = F^-1 marginalised over all other "
                             "parameters; augur_get_FoM_all scales Cov by chi2.ppf(CL,2) (= DETF/scale)",
           "derived": {}}
    if derived_params and not (out.get("transform_S8") or out.get("transform_Omega_m")):
        fom["derived"]["no_prior"] = _derived_sigmas(F, names, cosmo_fid) if pos_def else {}
        if Fp is not None:
            fom["derived"]["with_prior"] = _derived_sigmas(Fp, names, cosmo_fid)
    fom_path = outdir / f"fom_{slug}.json"
    write_json(fom_path, fom)
    files.append(str(fom_path))
    bias_meta = None
    if out.get("bias"):
        b = out["bias"]
        shift = np.asarray(b["shift"], dtype=float)
        b_path = outdir / f"fisher_bias_{slug}.csv"
        _write_table(b_path, [f"label: Fisher bias ({label})", "quantity: fisher_bias",
                              "units: parameter units; bias_over_sigma uses the no-prior sigma",
                              f"bias_params: {b['bias_params']}"],
                     {"param": names, "fiducial": fid, "bias": [float(x) for x in shift],
                      "sigma_no_prior": [float(s) for s in sig],
                      "bias_over_sigma": [float(x / s) if s > 0 else float("nan") for x, s in zip(shift, sig)]})
        files.append(str(b_path))
        bias_meta = {"bias_params": b["bias_params"], "shift": dict(zip(names, map(float, shift))),
                     "shift_over_sigma": {n: float(x / s) if s > 0 else None for n, x, s in zip(names, shift, sig)}}
    sacc_local = out["sacc_path"] if computed_on == "local" and os.path.isfile(out["sacc_path"]) else None
    if sacc_local:
        files.append(sacc_local)

    metadata = {"computed_on": computed_on, "params": names, "fiducials": dict(zip(names, fid)),
                "sigma_no_prior": fom["sigma_no_prior"], "sigma_with_prior": fom["sigma_with_prior"],
                "priors": priors, "fom": {"no_prior": fom["no_prior"], "with_prior": fom["with_prior"]},
                "derived": fom["derived"], "fisher_bias": bias_meta,
                "checks": {"symmetric_rel_err": sym_err, "positive_definite": pos_def,
                           "condition_number": cond, "min_eigenvalue": float(eig.min())},
                "n_data": out["n_data_likelihood"], "n_evaluations": out["n_evaluations"],
                "derivative_method": out["derivative_method"], "step_absolute": out["step"],
                "cov_type": out["cov_type"], "timing_s": out.get("timing_s"), "versions": out.get("versions"),
                "augur_text_outputs": [out.get("augur_output"), out.get("augur_fid_output")],
                "validator_warnings": warns}
    if out.get("_env_check"):
        metadata["env_check"] = out["_env_check"]
    if out.get("_artifact_files"):
        metadata["remote_artifact_files"] = out["_artifact_files"]
    sig_txt = ", ".join(f"{n}={s:.3g}" for n, s in zip(names, sig))
    msg = (f"Fisher matrix for {len(names)} parameters from {out['n_data_likelihood']} data points "
           f"({out['n_evaluations']} evaluations, {out.get('timing_s', {}).get('fisher', 0):.0f} s on {computed_on}). "
           f"Marginalised sigma (no prior): {sig_txt}.")
    if fom["no_prior"] and fom["no_prior"].get("detf_fom"):
        msg += f" DETF w0-wa FoM: {fom['no_prior']['detf_fom']:.1f}"
        if fom["with_prior"] and fom["with_prior"].get("detf_fom"):
            msg += f" (with priors {fom['with_prior']['detf_fom']:.1f})"
        msg += "."
    if not pos_def:
        msg += " WARNING: Fisher matrix is not positive definite (degenerate parameters or noisy derivatives)."
    return ArtifactResult(status="success", files=files, message=msg, metadata=metadata)


