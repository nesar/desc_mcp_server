def _write_table(path: Path, header_lines: list[str], columns: dict[str, list]) -> None:
    """CSV with '# key: value' headers that allows string columns (write_csv is float-only)."""
    n = len(next(iter(columns.values())))
    with path.open("w", encoding="utf-8") as f:
        for line in header_lines:
            f.write(f"# {line}\n")
        f.write(",".join(columns.keys()) + "\n")
        for i in range(n):
            cells = []
            for v in columns.values():
                x = v[i]
                cells.append(f"{x:.8g}" if isinstance(x, (float, np.floating)) else str(x))
            f.write(",".join(cells) + "\n")


def _write_fisher_csv(path: Path, names: list[str], F: np.ndarray, fiducials: list[float],
                      priors: dict, label: str, extra: list[str]) -> None:
    header = [f"label: {label}", "quantity: fisher_matrix",
              f"params: {','.join(names)}", "units: (parameter units)^-2; rows/columns in params order"]
    header += [f"fiducial_{n}: {v:.10g}" for n, v in zip(names, fiducials)]
    header += [f"prior_{n}: {priors[n]:.6g}" for n in names if n in priors]
    header += extra
    cols = {"param": list(names)}
    for j, n in enumerate(names):
        cols[n] = [float(F[i, j]) for i in range(len(names))]
    _write_table(path, header, cols)


def read_fisher_csv(path_str: str) -> tuple[list[str], np.ndarray, dict, dict]:
    """Read a fisher.csv written here -> (names, F, fiducials{name: value}, header dict).

    Also accepts a plain whitespace matrix (augur's fisher.dat) when a
    companion ``<stem>.names`` or augur ``fiducials.dat`` is NOT available:
    names become p0..pN and fiducials 0.
    """
    path = Path(path_str).expanduser().resolve()
    lines = path.read_text(encoding="utf-8").splitlines()
    header: dict[str, str] = {}
    i = 0
    for i, line in enumerate(lines):
        if not line.startswith("#"):
            break
        key, _, value = line.lstrip("# ").partition(":")
        header[key.strip()] = value.strip()
    body = [ln for ln in lines[i:] if ln.strip()]
    if "," in body[0] and body[0].split(",")[0].strip() == "param":
        names = [c.strip() for c in body[0].split(",")[1:]]
        F = np.array([[float(x) for x in ln.split(",")[1:]] for ln in body[1:]], dtype=float)
    else:  # plain matrix
        F = np.loadtxt(body, ndmin=2)
        names = header.get("params", "").split(",") if header.get("params") else \
            [f"p{k}" for k in range(F.shape[0])]
    fid = {n: float(header.get(f"fiducial_{n}", 0.0)) for n in names}
    return names, F, fid, header


def _ellipse(cov2: np.ndarray, CL: float) -> tuple[float, float, float]:
    """(width, height, angle_deg) of the CL ellipse for a 2x2 covariance (augur's formula)."""
    from scipy.stats import chi2
    C = chi2.ppf(CL, 2) * cov2
    D = np.sqrt((C[0, 0] - C[1, 1]) ** 2 + 4 * C[0, 1] ** 2)
    w = 2 * np.sqrt(max(0.5 * (C[0, 0] + C[1, 1] + D), 0))
    h = 2 * np.sqrt(max(0.5 * (C[0, 0] + C[1, 1] - D), 0))
    ang = np.rad2deg(0.5 * np.arctan2(2 * C[0, 1], C[0, 0] - C[1, 1]))
    return float(w), float(h), float(ang)


def _fom_block(F: np.ndarray, names: list[str]) -> dict | None:
    """DETF FoM and augur's get_FoM_all for (w0, wa) when both are varied."""
    if "w0" not in names or "wa" not in names:
        return None
    iw, iwa = names.index("w0"), names.index("wa")
    cov = np.linalg.inv(F)
    sub = cov[np.ix_([iw, iwa], [iw, iwa])]
    det = float(np.linalg.det(sub))
    out = {"detf_fom": float(1.0 / np.sqrt(det)) if det > 0 else None,
           "sigma_w0": float(np.sqrt(cov[iw, iw])), "sigma_wa": float(np.sqrt(cov[iwa, iwa])),
           "rho_w0_wa": float(sub[0, 1] / np.sqrt(sub[0, 0] * sub[1, 1])),
           "augur_get_FoM_all": {}}
    try:
        from augur.postprocess import get_FoM_all
    except Exception:  # noqa: BLE001 - fall back to the same arithmetic
        from scipy.stats import chi2

        def get_FoM_all(fisher, p1, p2, CL):
            s = chi2.ppf(CL, 2)
            inv = s * np.linalg.inv(fisher)
            fom = 1.0 / np.sqrt(inv[p1, p1] * inv[p2, p2] - inv[p1, p2] * inv[p2, p1])
            fom2 = np.sqrt(np.linalg.det(np.linalg.inv(inv[np.ix_([p1, p2], [p1, p2])])))
            return fom, fom2
    for CL in (0.68, 0.95):
        fom, fom2 = get_FoM_all(F, iw, iwa, CL)
        out["augur_get_FoM_all"][f"CL{CL:g}"] = {"FoM": float(fom), "FoM_alt": float(fom2)}
    return out


def _derived_sigmas(F: np.ndarray, names: list[str], cosmo: dict) -> dict:
    """sigma(Omega_m) and sigma(S8) by linear propagation of Cov = F^-1."""
    cov = np.linalg.inv(F)
    h = float(cosmo.get("h", 0.67))
    Oc, Ob = float(cosmo.get("Omega_c", 0.25)), float(cosmo.get("Omega_b", 0.05))
    mnu = float(cosmo.get("m_nu", 0.0) or 0.0)
    Onu = mnu / (93.14 * h ** 2)
    Om = Oc + Ob + Onu
    out = {}
    g_om = np.zeros(len(names))
    for k, n in enumerate(names):
        if n == "Omega_c" or n == "Omega_b":
            g_om[k] = 1.0
        elif n == "m_nu":
            g_om[k] = 1.0 / (93.14 * h ** 2)
        elif n == "h":
            g_om[k] = -2.0 * Onu / h
    if "Omega_c" in names and "Omega_m" not in names:
        out["Omega_m"] = {"fiducial": Om, "sigma": float(np.sqrt(g_om @ cov @ g_om))}
    s8 = cosmo.get("sigma8")
    if s8 is not None and "sigma8" in names and "S8" not in names:
        s8 = float(s8)
        S8 = s8 * np.sqrt(Om / 0.3)
        g = g_om * (s8 / (2.0 * np.sqrt(0.3 * Om)))
        g[names.index("sigma8")] += np.sqrt(Om / 0.3)
        out["S8"] = {"fiducial": float(S8), "sigma": float(np.sqrt(g @ cov @ g))}
    return out


def _inline_files_for_remote(config: dict) -> dict:
    """n(z) tables and the SRD covariance as JSON payload (server paths do not exist on the node)."""
    import base64
    files = {}
    for section in ("sources", "lenses"):
        kw = (config.get(section) or {}).get("Nz_kwargs") or {}
        p = kw.get("input_file")
        if p and os.path.isfile(p):
            if "npy" in str(kw.get("format", "npy")) and p.endswith(".npy"):
                files[os.path.basename(p)] = {"kind": "npy_b64",
                                              "data": base64.b64encode(Path(p).read_bytes()).decode()}
            else:
                files[os.path.basename(p)] = {"kind": "ascii", "data": np.loadtxt(p).tolist()}
    p = (config.get("cov_options") or {}).get("SRD_cov_path")
    if p and os.path.isfile(p):
        size = os.path.getsize(p)
        if size > 6 * 1024 * 1024:
            raise ValueError(
                f"SRD covariance {p} is {size / 1e6:.1f} MB - too large to embed in a remote kernel "
                "call. Use cov_type gaus_internal/tjpcov for remote runs, or run this tool locally.")
        files[os.path.basename(p)] = {"kind": "npy_b64",
                                      "data": base64.b64encode(Path(p).read_bytes()).decode()}
    return files


def _run_forecast_kernel(config: dict, mode: str, env_setup: str | None, duration: int,
                         include_bias=None, max_cov_return: int = 600) -> tuple[dict, str]:
    """Run tools.inner.augur_forecast.main locally or on the active dispatch site."""
    from mcp_server.dispatch import remote_site, run_env_kernel  # lazy: server-only

    site = remote_site()
    params = {"config": copy.deepcopy(config), "mode": mode, "include_bias": include_bias,
              "max_cov_return": max_cov_return}
    if site:
        if not env_setup or not env_setup.strip():
            raise ValueError(
                f"Dispatch is set to {site}: this call needs env_setup, a shell snippet that "
                "activates a facility environment with augur + firecrown >= 1.14 (see "
                "export_dispatch_pack -> env_kernel.env_setup_candidates, e.g. the NERSC "
                "desc-python activation). Nothing is chosen by the server.")
        params["inline_files"] = _inline_files_for_remote(config)
        params["relocate_outputs"] = True
        res = run_env_kernel(env_setup, "augur_forecast", params, duration=duration)
        out = res["result"]["result"]
        out["_env_check"] = res["result"].get("env_check")
        out["_artifact_files"] = res.get("artifact_files")
        return out, str(res.get("host", site))
    from ..inner.augur_forecast import main as _main
    params["job_dir"] = os.path.dirname(os.path.abspath(str(config["fiducial_sacc_path"])))
    return _main(params), "local"


