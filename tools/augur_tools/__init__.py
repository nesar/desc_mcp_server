def _render_yaml_text(path: Path) -> dict:
    """Load a YAML config; render ``{{ env['AUGUR_DIR'] }}`` Jinja tags like augur's parser."""
    import yaml
    text = path.read_text(encoding="utf-8")
    if "{{" in text:
        env = dict(os.environ)
        clone = clone_dir("augur")
        if clone is not None:
            env.setdefault("AUGUR_DIR", str(clone))
        try:
            import jinja2
            text = jinja2.Template(text).render(env=env)
        except ImportError:
            text = text.replace("{{ env['AUGUR_DIR'] }}", env.get("AUGUR_DIR", ""))
    return yaml.safe_load(text)


def _load_config(config_path: str) -> dict:
    path = Path(config_path).expanduser().resolve()
    if not path.is_file():
        raise FileNotFoundError(f"config not found: {path}")
    cfg = _render_yaml_text(path)
    if not isinstance(cfg, dict):
        raise ValueError(f"{path} did not parse to a mapping")
    return cfg


