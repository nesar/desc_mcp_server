def _srd_layout_check(cfg: dict, year: str) -> list[str]:
    """Why a config does NOT match the SRD covariance layout for `year` ('' if it does)."""
    preset = SRD_PRESETS[year]
    problems = []
    ns = (cfg.get("sources") or {}).get("nbins")
    nl = (cfg.get("lenses") or {}).get("nbins")
    if ns != preset["n_source_bins"] or nl != preset["n_lens_bins"]:
        problems.append(f"SRD {year} covariance needs {preset['n_source_bins']} source + "
                        f"{preset['n_lens_bins']} lens bins, config has {ns} + {nl}")
    stats = cfg.get("statistics") or {}
    want = {"galaxy_shear_cl_ee": _pairs_all(5, 5, True),
            "galaxy_shearDensity_cl_e": preset["ggl_pairs"],
            "galaxy_density_cl": [[i, i] for i in range(preset["n_lens_bins"])]}
    for key, pairs in want.items():
        if key not in stats:
            problems.append(f"SRD covariance needs statistic {key} (all three 3x2pt statistics)")
            continue
        got = [list(p) for p in stats[key].get("tracer_combs", [])]
        if sorted(got) != sorted([list(p) for p in pairs]):
            problems.append(f"{key}.tracer_combs differ from the SRD {year} pair list ({len(pairs)} pairs)")
        try:
            edges = _parse_edges(stats[key].get("ell_edges"))
            if len(edges) - 1 != 20:
                problems.append(f"{key}: SRD covariance has 20 ell bands, config has {len(edges) - 1}")
        except Exception as exc:  # noqa: BLE001
            problems.append(f"{key}.ell_edges unparsable: {exc}")
    return problems


def _validate(cfg: dict) -> tuple[list[str], list[str], dict]:
    errors: list[str] = []
    warnings: list[str] = []
    info: dict = {}

    for key in ("cosmo", "statistics", "cov_options", "fiducial_sacc_path"):
        if key not in cfg:
            errors.append(f"missing top-level key '{key}'")
    if "general" not in cfg:
        warnings.append("no 'general' section: defaults ignore_scale_cuts=False, "
                        "ignore_scale_cuts_likelihood=False")
    cosmo = cfg.get("cosmo") or {}
    has_s8 = cosmo.get("sigma8") is not None
    has_as = cosmo.get("A_s") is not None
    if has_s8 == has_as:
        errors.append("cosmo must give exactly one of sigma8 / A_s")
    tf = str(cosmo.get("transfer_function", "boltzmann_camb")).lower()
    if tf == "boltzmann_isitgr":
        warnings.append("transfer_function boltzmann_isitgr (MG) is outside augur's registry and "
                        "falls back to CAMB settings; only mu_Sigma MG configs use it")
    elif tf not in TRANSFER_REGISTRY:
        errors.append(f"cosmo.transfer_function {tf!r} not in augur registry {TRANSFER_REGISTRY}")
    if tf in ("eisenstein_hu", "eh", "bbks") and has_as:
        errors.append(f"transfer_function {tf} cannot use A_s (analytic transfer functions need sigma8)")
    if tf == "boltzmann_camb":
        hv = ((cosmo.get("extra_parameters") or {}).get("camb") or {}).get("halofit_version")
        if not hv and str(cosmo.get("matter_power_spectrum", "halofit")).lower() != "linear":
            errors.append("transfer_function boltzmann_camb requires cosmo.extra_parameters.camb."
                          "halofit_version (e.g. takahashi, mead2020_feedback)")
    mps = str(cosmo.get("matter_power_spectrum", "halofit")).lower()
    if mps not in ("halofit", "linear", "camb"):
        errors.append(f"cosmo.matter_power_spectrum {mps!r}: augur supports halofit, linear (or camb with CAMB)")

    gen = cfg.get("general") or {}
    ign = bool(gen.get("ignore_scale_cuts", False))
    ign_lk = bool(gen.get("ignore_scale_cuts_likelihood", False))
    if (not ign) and ign_lk:
        errors.append("general: ignore_scale_cuts=False with ignore_scale_cuts_likelihood=True raises in augur")
    if ign_lk and "Firecrown_Factory" in cfg:
        errors.append("general.ignore_scale_cuts_likelihood=True with a Firecrown_Factory makes augur fall "
                      "back to a bare ConstGaussian likelihood WITHOUT systematics; set it to False")
    if str(gen.get("bandpower_windows", "None")) == "NaMaster":
        errors.append("general.bandpower_windows NaMaster is not implemented in augur")
    if "Firecrown_Factory" not in cfg:
        warnings.append("no Firecrown_Factory: augur uses the legacy ConstGaussian path with no "
                        "systematics (no IA, delta_z, m, galaxy bias updates)")
    else:
        if len(cfg["Firecrown_Factory"]) != 1 or "TwoPointFactory" not in cfg["Firecrown_Factory"]:
            errors.append("Firecrown_Factory must contain exactly one key: TwoPointFactory")

    # tracers
    nbins = {}
    for section, kind in (("sources", "src"), ("lenses", "lens")):
        blk = cfg.get(section)
        if not blk:
            continue
        n = blk.get("nbins")
        if not isinstance(n, int) or n < 1:
            errors.append(f"{section}.nbins must be a positive integer")
            continue
        nbins[kind] = n
        nd = blk.get("ndens")
        if nd is None or (isinstance(nd, (int, float)) and nd <= 0):
            errors.append(f"{section}.ndens must be > 0 [arcmin^-2]")
        if isinstance(nd, list) and len(nd) != n:
            errors.append(f"{section}.ndens list length {len(nd)} != nbins {n}")
        if section == "sources" and blk.get("ellipticity_error") is None:
            errors.append("sources.ellipticity_error (sigma_e) is required for the noise power")
        nz_type = blk.get("Nz_type")
        types = nz_type if isinstance(nz_type, list) else [nz_type]
        for t in types:
            if t not in NZ_REGISTRY:
                errors.append(f"{section}.Nz_type {t!r} not in augur registry {NZ_REGISTRY} "
                              "(TopHat/Gaussian are documented but unregistered)")
        kw = blk.get("Nz_kwargs") or {}
        if "ZDistFromFile" in types:
            p = kw.get("input_file")
            if not p:
                errors.append(f"{section}: ZDistFromFile needs Nz_kwargs.input_file")
            else:
                if "{{" in str(p):
                    errors.append(f"{section}.Nz_kwargs.input_file still contains a Jinja tag: {p}")
                elif not os.path.isabs(str(p)):
                    warnings.append(f"{section}.Nz_kwargs.input_file is relative ({p}); augur resolves it "
                                    "against the process cwd")
                if not os.path.isfile(str(p)):
                    errors.append(f"{section}: n(z) file not found: {p}")
                elif "ascii" in str(kw.get("format", "npy")):
                    try:
                        ncol = np.loadtxt(str(p), max_rows=2).shape[1]
                        if ncol < n + 1:
                            errors.append(f"{section}: {p} has {ncol - 1} n(z) columns < nbins {n}")
                    except Exception as exc:  # noqa: BLE001
                        errors.append(f"{section}: cannot read {p}: {exc}")
        if "LensSRD2018" in types:
            c = kw.get("Nz_center")
            try:
                nc = len(_parse_edges(c)) if c is not None else 0
            except Exception:  # noqa: BLE001
                nc = -1
            if nc != n:
                errors.append(f"{section}: LensSRD2018 Nz_center has {nc} entries, nbins is {n}")
            for need in ("Nz_width", "Nz_sigmaz"):
                if need not in kw:
                    errors.append(f"{section}: LensSRD2018 needs Nz_kwargs.{need}")
        if "SourceSRD2018" in types and "Nz_sigmaz" not in kw:
            errors.append(f"{section}: SourceSRD2018 needs Nz_kwargs.Nz_sigmaz")

    # statistics
    stats = cfg.get("statistics") or {}
    n_data = 0
    edges_seen = []
    for key, scfg in stats.items():
        if key not in DATA_TYPES:
            errors.append(f"statistics.{key}: unknown data type (augur generates "
                          f"{sorted(DATA_TYPES)} only; real-space statistics are not available)")
            continue
        if not isinstance(scfg, dict):
            errors.append(f"statistics.{key} must be a mapping")
            continue
        k1, k2 = DATA_TYPES[key]
        combs = scfg.get("tracer_combs") or []
        if not combs:
            errors.append(f"statistics.{key}.tracer_combs is empty")
        for comb in combs:
            if len(comb) != 2:
                errors.append(f"statistics.{key}: tracer comb {comb} must have two indices")
                continue
            for idx, kind in zip(comb, (k1, k2)):
                if kind not in nbins:
                    errors.append(f"statistics.{key} needs a '{'sources' if kind == 'src' else 'lenses'}' section")
                elif not (0 <= int(idx) < nbins[kind]):
                    errors.append(f"statistics.{key}: {kind}{idx} out of range (nbins={nbins[kind]})")
        if "kmax" in scfg and "lmax" in scfg:
            errors.append(f"statistics.{key}: give kmax [Mpc^-1] OR lmax, not both keys (augur raises "
                          "even when one of them is None)")
        km = scfg.get("kmax")
        if isinstance(km, (int, float)) and not isinstance(km, bool) and km > 1.0:
            warnings.append(f"statistics.{key}.kmax={km} Mpc^-1 is very nonlinear (SRD uses ~0.2)")
        try:
            edges = _parse_edges(scfg.get("ell_edges"))
            if len(edges) < 2 or np.any(np.diff(edges) <= 0):
                errors.append(f"statistics.{key}.ell_edges must be increasing with >= 2 values")
            n_data += len(combs) * (len(edges) - 1)
            edges_seen.append(edges)
        except Exception as exc:  # noqa: BLE001
            errors.append(f"statistics.{key}.ell_edges unparsable: {exc}")
    if len(edges_seen) > 1 and any(e.shape != edges_seen[0].shape or not np.allclose(e, edges_seen[0])
                                   for e in edges_seen[1:]):
        msg = "ell_edges differ between statistics"
        if (cfg.get("cov_options") or {}).get("cov_type") == "gaus_internal":
            errors.append(msg + " - gaus_internal assumes identical edges for all probes")
        else:
            warnings.append(msg)
    info["n_data_before_cuts"] = n_data

    # covariance
    cov = cfg.get("cov_options") or {}
    ct = cov.get("cov_type")
    if ct not in ("gaus_internal", "SRD", "tjpcov"):
        errors.append(f"cov_options.cov_type {ct!r} must be gaus_internal, SRD or tjpcov "
                      "(anything else silently yields an identity covariance)")
    if ct in ("gaus_internal", "tjpcov"):
        fs = cov.get("fsky")
        if not isinstance(fs, (int, float)) or not (0 < fs <= 1):
            errors.append("cov_options.fsky must be in (0, 1]")
    if ct == "SRD":
        p = cov.get("SRD_cov_path")
        if not p:
            errors.append("cov_type SRD needs cov_options.SRD_cov_path")
        else:
            if "{{" in str(p):
                errors.append(f"SRD_cov_path still contains a Jinja tag: {p}")
            elif not os.path.isfile(str(p)):
                errors.append(f"SRD covariance file not found: {p}")
            year = "Y10" if "Y10" in str(p) else "Y1"
            info["srd_year_from_path"] = year
            errors += _srd_layout_check(cfg, year)
    if ct == "tjpcov":
        te = (cov.get("binning_info") or {}).get("ell_edges")
        if te is None:
            errors.append("cov_type tjpcov needs cov_options.binning_info.ell_edges equal to the statistics' edges")
        elif edges_seen:
            try:
                tedges = _parse_edges(te)
                if tedges.shape != edges_seen[0].shape or not np.allclose(tedges, edges_seen[0]):
                    errors.append("cov_options.binning_info.ell_edges must equal statistics.*.ell_edges exactly")
            except Exception as exc:  # noqa: BLE001
                errors.append(f"cov_options.binning_info.ell_edges unparsable: {exc}")
    sp = cfg.get("fiducial_sacc_path")
    if sp and not os.path.isabs(str(sp)):
        warnings.append(f"fiducial_sacc_path is relative ({sp}); written relative to the process cwd")

    # fisher
    fisher = cfg.get("fisher")
    if fisher:
        sys_keys = set((cfg.get("systematics") or {}).keys())
        known = set(COSMO_KEYS) | sys_keys
        if "var_pars" in fisher:
            var_pars = list(fisher["var_pars"])
        elif "parameters" in fisher:
            var_pars = list(fisher["parameters"].keys())
            if "postprocess" in cfg:
                warnings.append("fisher.parameters mode + postprocess: augur's postprocess reads "
                                "fisher.var_pars and will KeyError")
        else:
            var_pars = []
            errors.append("fisher needs var_pars (list) or parameters (name: [min, fid, max])")
        if len(set(var_pars)) != len(var_pars):
            errors.append("fisher.var_pars has duplicates")
        for v in var_pars:
            if v not in known:
                errors.append(f"var_pars entry {v!r} is neither a CCL cosmology key nor in systematics")
        if "sigma8" in var_pars and "A_s" in var_pars:
            errors.append("var_pars lists both sigma8 and A_s")
        if "sigma8" in var_pars and not has_s8:
            errors.append("sigma8 in var_pars but the fiducial cosmology uses A_s")
        if "A_s" in var_pars and not has_as:
            errors.append("A_s in var_pars but the fiducial cosmology uses sigma8")
        t_om = bool(fisher.get("transform_Omega_m", False))
        t_s8 = bool(fisher.get("transform_S8", False))
        if t_om and "Omega_c" not in var_pars:
            errors.append("transform_Omega_m requires Omega_c in var_pars")
        if t_s8 and "sigma8" not in var_pars:
            errors.append("transform_S8 requires sigma8 in var_pars")
        priors = fisher.get("gaussian_priors") or {}
        bad = [p for p in priors if not (p in var_pars or (p == "Omega_m" and t_om) or (p == "S8" and t_s8))]
        if bad:
            errors.append(f"gaussian_priors for parameters not in var_pars (augur raises ValueError): "
                          f"{bad} - remove them or add them to var_pars")
        if t_om and "Omega_m" in priors and "Omega_c" in priors:
            errors.append("priors on both Omega_c and Omega_m")
        if t_s8 and "S8" in priors and "sigma8" in priors:
            errors.append("priors on both sigma8 and S8")
        for p, s in priors.items():
            if not isinstance(s, (int, float)) or s <= 0:
                errors.append(f"gaussian_priors.{p} must be a positive width")
        step = fisher.get("step", 0.01)
        try:
            step = float(step)
            if step <= 0:
                errors.append("fisher.step must be > 0")
            elif step < 1e-4:
                warnings.append(f"fisher.step={step:g} is ABSOLUTE and tiny: with CCL splines the "
                                "derivatives can be noise dominated (1e-3..1e-2 is safer)")
            elif step >= 0.1:
                warnings.append(f"fisher.step={step:g} is large for parameters like Omega_b or delta_z")
        except (TypeError, ValueError):
            errors.append("fisher.step must be numeric")
        method = fisher.get("derivative_method", "numdifftools")
        if method not in ("numdifftools", "5pt_stencil", "derivkit"):
            errors.append(f"fisher.derivative_method {method!r} not in numdifftools/5pt_stencil/derivkit")
        for key in ("output", "fid_output"):
            p = fisher.get(key)
            if not p:
                errors.append(f"fisher.{key} is required (augur writes text outputs there)")
            elif not os.path.isabs(str(p)):
                warnings.append(f"fisher.{key} is relative ({p}); augur writes it relative to the cwd")
        fb = fisher.get("fisher_bias")
        if fb:
            if t_om or t_s8:
                errors.append("fisher_bias cannot be combined with transform_S8/transform_Omega_m")
            bp = fb.get("bias_params") or {}
            bdv = fb.get("biased_dv") or ""
            if not bp and not (bdv and os.path.isfile(str(bdv))):
                errors.append("fisher_bias needs bias_params or an existing biased_dv file")
            for p in bp:
                if p not in known:
                    errors.append(f"fisher_bias.bias_params.{p} is not a cosmology or systematics parameter")
        n = len(var_pars)
        evals = {"numdifftools": 2 * n + 1, "5pt_stencil": 4 * n + 1, "derivkit": 27 * n}.get(method, 2 * n + 1)
        info.update({"n_var_pars": n, "var_pars": var_pars, "n_priors_applied": len(priors) - len(bad),
                     "estimated_likelihood_evaluations": evals + 1 + (2 if fb else 0),
                     "derivative_method": method, "step": step})
    return errors, warnings, info


