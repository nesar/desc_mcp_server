"""Smokescreen tools: data-vector concealment (blinding) with a firecrown likelihood.

Smokescreen (github.com/LSSTDESC/Smokescreen) implements the Muir et al.
(2021) scheme: the data vector is shifted by the difference (or ratio)
between the theory at a hidden cosmology and the theory at the reference
cosmology, so the analysis runs on a data vector whose cosmology is unknown
to the analyst. The hidden cosmology is drawn from the ranges you give with
a seed; everything that would reveal it (the drawn values, the seed) is
kept OUT of this server's outputs, messages and metadata.

This family builds on the firecrown family: the likelihood is the
experiment YAML from firecrown_build_likelihood (a tiny generated module
wraps it in the `build_likelihood` form Smokescreen expects). Originals are
never deleted or modified; concealed and encrypted files are new files in
output_dir. Package name `smokescreen_tools` avoids shadowing the library.
"""

import contextlib
import datetime as _dt
import sys
from pathlib import Path
from typing import Annotated, Literal

import numpy as np
from pydantic import Field, validate_call

from ..common import ArtifactResult, param_slug, resolve_outdir, write_json
from ..cosmology import CosmologyParams
from ..firecrown_tools import _check_point, _exp_path, _load_local, _sacc_path_from_yaml
from ..sacc_tools import _load as _load_sacc

__all__ = ["smokescreen_conceal_datavector", "smokescreen_inspect",
           "smokescreen_encrypt_file", "smokescreen_decrypt_file"]

CONVENTIONS = {
    "method": "Muir et al. 2021 data-vector concealment: d_concealed = d + [t(theta_hidden) - t(theta_ref)] "
              "(shift_type add) or d * t(theta_hidden)/t(theta_ref) (mult); t = firecrown theory vector",
    "shifts": "per cosmological parameter (pyccl names: Omega_c Omega_b h n_s sigma8|A_s Omega_k Neff m_nu w0 wa): "
              "[lo, hi] = hidden value drawn uniformly in [lo, hi] (ABSOLUTE values, not offsets) with "
              "shift_distribution 'flat'; [mean, std] with 'gaussian'; a single number = deterministic "
              "hidden value = reference + number (a test mode, not concealment)",
    "likelihood": "the experiment YAML from firecrown_build_likelihood; the experiment must keep EVERY point "
                  "of the sacc file (no scale cuts) because Smokescreen checks the data vector against the file",
    "seed": "any string or integer; the same seed, ranges and reference reproduce the same hidden cosmology - "
            "treat it as the secret. The tools never echo it; it does appear in the chat where you typed it",
    "outputs": "the concealed sacc carries metadata concealed=true, creator, creation, info; a record JSON "
               "lists the shifted parameters and ranges (never the drawn values)",
    "encryption": "Fernet (symmetric) via smokescreen.encryption: <stem>.encrpt + <stem>.key; originals kept",
}
CAVEATS = [
    "Smokescreen stores the seed in the concealed file's metadata (seed_smokescreen) - upstream behaviour. "
    "With the ranges, that reproduces the hidden cosmology: do not share the concealed file together with "
    "the ranges and expect concealment to hold. smokescreen_inspect flags it.",
    "Nuisance parameters are held at the reference values for both theory evaluations (firecrown "
    "defaults made neutral, overridden by `nuisance`); only cosmological parameters are concealed.",
    "The amplitude parameter you shift (sigma8 or A_s) must be the one the experiment samples "
    "(firecrown_build_likelihood amplitude_parameter); a sigma8 shift on an A_s experiment is refused.",
    "A multiplicative shift divides by the reference theory: zero-crossing statistics (xi_-, cross spectra) "
    "make it ill-defined - prefer 'add' for 3x2pt.",
    "A deterministic single-value shift is reproducible by construction - use it only to validate a pipeline.",
    "Originals are never deleted by these tools (Smokescreen's CLI deletes them by default); delete or "
    "move the original yourself if the analysis protocol requires it.",
]

_CCL_PARAMS = ("Omega_c", "Omega_b", "h", "n_s", "sigma8", "A_s", "Omega_k", "Neff", "m_nu", "w0", "wa")

_LIKELIHOOD_MODULE = '''"""firecrown likelihood module generated by desc-mcp-server (smokescreen_conceal_datavector).

Wraps a TwoPointExperiment YAML in the build_likelihood() form Smokescreen
expects. The sacc file comes from the YAML (data_source.sacc_data_file);
build_parameters is accepted for the interface and otherwise unused.
"""
EXPERIMENT_YAML = {yaml!r}


def build_likelihood(build_parameters=None):
    import warnings

    from firecrown.likelihood.factories import TwoPointExperiment
    from firecrown.modeling_tools import ModelingTools

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        exp = TwoPointExperiment.load_from_yaml(EXPERIMENT_YAML)
        like = exp.make_likelihood()
        tools = ModelingTools(ccl_factory=exp.ccl_factory)
    return like, tools
'''


def _amplitude_of(exp_path: Path) -> str:
    import yaml

    doc = yaml.safe_load(exp_path.read_text(encoding="utf-8")) or {}
    amp = str(((doc.get("ccl_factory") or {}).get("amplitude_parameter") or "sigma8")).lower()
    return "A_s" if amp in ("a_s", "as") else "sigma8"


def _sniff_format(data: bytes) -> str:
    if data[:8] == b"\x89HDF\r\n\x1a\n":
        return "hdf5"
    if data[:6] == b"SIMPLE":
        return "fits"
    return "unknown"


